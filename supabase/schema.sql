-- PaperGuide AI schema. Run in the Supabase SQL editor.
create extension if not exists "pgcrypto";

create table if not exists public.documents (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  original_filename text not null,
  storage_path text not null unique,
  page_count integer check (page_count is null or page_count >= 0),
  status text not null default 'processing' check (status in ('processing', 'ready', 'failed')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.document_pages (
  id bigint generated by default as identity primary key,
  document_id uuid not null references public.documents(id) on delete cascade,
  page_number integer not null check (page_number >= 1),
  text text not null default '',
  detected_headings jsonb not null default '[]'::jsonb,
  detected_references jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  unique (document_id, page_number)
);

create table if not exists public.reading_routes (
  id uuid primary key default gen_random_uuid(),
  document_id uuid not null references public.documents(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  route jsonb not null,
  created_at timestamptz not null default now()
);

create table if not exists public.podcast_scripts (
  id uuid primary key default gen_random_uuid(),
  document_id uuid not null references public.documents(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  episode_title text not null,
  duration_minutes integer not null default 8 check (duration_minutes between 1 and 60),
  script text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.notes (
  id uuid primary key default gen_random_uuid(),
  document_id uuid not null references public.documents(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  content text not null check (length(content) > 0),
  page_number integer check (page_number is null or page_number >= 1),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.audio_generations (
  id uuid primary key default gen_random_uuid(),
  document_id uuid not null references public.documents(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  storage_path text not null unique,
  voice text not null,
  model text not null,
  created_at timestamptz not null default now()
);

create index if not exists documents_user_created_idx on public.documents(user_id, created_at desc);
create index if not exists document_pages_document_idx on public.document_pages(document_id, page_number);
create index if not exists reading_routes_document_idx on public.reading_routes(document_id, created_at desc);
create index if not exists podcast_scripts_document_idx on public.podcast_scripts(document_id, created_at desc);
create index if not exists notes_document_idx on public.notes(document_id, created_at desc);
create index if not exists audio_generations_document_idx on public.audio_generations(document_id, created_at desc);

create or replace function public.set_updated_at()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists documents_set_updated_at on public.documents;
create trigger documents_set_updated_at before update on public.documents for each row execute function public.set_updated_at();
drop trigger if exists notes_set_updated_at on public.notes;
create trigger notes_set_updated_at before update on public.notes for each row execute function public.set_updated_at();

alter table public.documents enable row level security;
alter table public.document_pages enable row level security;
alter table public.reading_routes enable row level security;
alter table public.podcast_scripts enable row level security;
alter table public.notes enable row level security;
alter table public.audio_generations enable row level security;

drop policy if exists "Users manage own documents" on public.documents;
create policy "Users manage own documents" on public.documents for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Users read pages for own documents" on public.document_pages;
create policy "Users read pages for own documents" on public.document_pages for select using (exists (select 1 from public.documents d where d.id = document_id and d.user_id = auth.uid()));

drop policy if exists "Users manage own reading routes" on public.reading_routes;
create policy "Users manage own reading routes" on public.reading_routes for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users manage own podcast scripts" on public.podcast_scripts;
create policy "Users manage own podcast scripts" on public.podcast_scripts for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users manage own notes" on public.notes;
create policy "Users manage own notes" on public.notes for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users manage own audio generations" on public.audio_generations;
create policy "Users manage own audio generations" on public.audio_generations for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

